data = [10, 20, 30, 40, 50, 60, 70, 80]
print("Початковий список:", data)

print("Елемент за додатним індексом 2:", data[2])
print("Елемент за від'ємним індексом -1:", data[-1])

print("Зріз 1 (перші 3 елементи):", data[:3])
print("Зріз 2 (від індексу 2 до 5):", data[2:5])
print("Зріз 3 (всі елементи з кроком 2):", data[::2])

data.append(90)
print("Після додавання елемента в кінець:", data)

data[1:3] = [25, 35]
print("Після заміни діапазону з індексу 1 до 3:", data)